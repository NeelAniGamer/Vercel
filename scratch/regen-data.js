// Three of the eleven old lines share the "Human-Empathy Protected" prefix but
// point at different fields (teaching, care work, clinical medicine), so they
// are matched on their body text instead.
function aiLineFor(career) {
  const raw = career.aiImpact || '';
  const prefix = raw.split('\u2014')[0].trim();
  if (prefix === 'Human-Empathy Protected') {
    if (/classroom|teaching|lesson/i.test(raw)) {
      return AI_LINES['Human-Empathy Protected'];
    }
    if (/diagnostic|bedside|clinical|imaging/i.test(raw)) {
      return {
        tag: 'people',
        label: 'Diagnostics Are Assisted',
        text: 'Imaging, lab results and records are increasingly read by software first. Examination, procedures, consent and the conversation with the patient are not.'
      };
    }
    return {
      tag: 'people',
      label: 'Presence Is The Job',
      text: 'Comfort, trust and physical care are the reason the role exists. Tools can monitor and remind, but they cannot sit with someone or speak for the family.'
    };
  }
  return AI_LINES[prefix] || { tag: 'automation', label: prefix, text: raw.split('\u2014').slice(1).join('\u2014').trim() || raw };
}

// ------------------------------------------------------------ text helpers ---
function sentences(s) {
  return (s.match(/[^.!?]+[.!?]+/g) || [s]).map(x => x.trim()).filter(Boolean);
}

function decap(s) {
  return s.charAt(0).toLowerCase() + s.slice(1);
}

function capFirst(s) {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

// "Accountants and auditors prepare and examine financial records."
//   -> "Prepare and examine financial records."
function taglineFrom(summary, title) {
  if (!summary) return '';
  const first = sentences(summary)[0] || summary;
  const t = title.toLowerCase();
  const s = first.toLowerCase();
  if (s.startsWith(t)) {
    const rest = first.slice(title.length).replace(/^[\s,:-]+/, '');
    if (rest.length > 8) return capFirst(rest);
  }
  // Subject is shorter than the page title ("Announcers present ..."): drop
  // just the leading word when it matches the title's first word.
  const firstWord = title.split(/\s+/)[0].toLowerCase();
  const words = first.split(' ');
  if (firstWord && words.length > 6 && s.startsWith(firstWord + ' ')) {
    const rest = words.slice(1).join(' ');
    if (rest.length > 12) return capFirst(rest);
  }
  return first;
}

// Card copy: everything after the first sentence of the overview, so the card
// does not repeat the tagline. Single-sentence overviews fall back to the BLS
// duty bullets, which read as work rather than a definition.
function descFrom(bls) {
  const overview = bls.overview || '';
  const parts = sentences(overview);
  let out = '';
  if (parts.length >= 2) {
    out = parts.slice(1).join(' ').trim();
    if (out.length < 60) out = parts.slice(0, 2).join(' ');
  } else if (bls.duties && bls.duties.length) {
    out = bls.duties.slice(0, 3).map(d => {
      const clean = d.replace(/[.;]+$/, '');
      return capFirst(clean);
    }).join('; ') + '.';
  } else {
    out = parts[0] || bls.summary || '';
  }
  if (out.length > 320) {
    const kept = sentences(out);
    let acc = '';
    for (const s of kept) {
      if ((acc + ' ' + s).trim().length > 320) break;
      acc = (acc + ' ' + s).trim();
    }
    out = acc || kept[0];
  }
  return out;
}

// ------------------------------------------------------- BLS field mapping ---
function growthLabel(pct, phrase, dir) {
  const p = (phrase || '').toLowerCase();
  if (dir === 'decline') return 'Decline';
  if (p.includes('much faster')) return 'Much faster than average';
  if (p.includes('faster than')) return 'Faster than average';
  if (p.includes('slower')) return 'Slower than average';
  if (p.includes('little or no change') || pct === 0) return 'Little or no change';
  if (p.includes('as fast')) return 'As fast as average';
  return 'As fast as average';
}

function demandFor(pct, dir) {
  if (dir === 'decline') return 'Falling';
  if (pct >= 20) return 'Extreme';
  if (pct >= 10) return 'Very High';
  if (pct >= 5) return 'High';
  return 'Steady';
}

// Keep the site's existing rupee convention: scale the whole old string by the
// ratio of the real BLS median to the guess it was built from.
function rescaleSalary(old, medianUsd) {
  if (!old || !medianUsd) return old;
  const usdParts = [...old.matchAll(/\$(\d+)K/g)].map(m => parseInt(m[1], 10));
  if (usdParts.length < 3) return old;
  const oldMid = usdParts[1];
  if (!oldMid) return old;
  const f = (medianUsd / 1000) / oldMid;
  const newUsd = [
    Math.max(1, Math.round((medianUsd * 0.72) / 1000)),
    Math.max(2, Math.round(medianUsd / 1000)),
    Math.max(3, Math.round((medianUsd * 1.9) / 1000))
  ];
  const inr = [...old.matchAll(/(\d+)-(\d+) LPA/g)].map(m => [
    Math.max(1, Math.round(parseInt(m[1], 10) * f)),
    Math.max(2, Math.round(parseInt(m[2], 10) * f))
  ]);
  const leadInr = old.match(/(\d+) LPA\+/);
  const lead = leadInr
    ? Math.max(3, Math.round(parseInt(leadInr[1], 10) * f))
    : Math.max(3, Math.round(newUsd[2] * 0.42));
  if (inr.length < 2) return old;
  return 'Entry: $' + newUsd[0] + 'K / \u20b9' + inr[0][0] + '-' + inr[0][1] + ' LPA \u00b7 ' +
    'Mid: $' + newUsd[1] + 'K / \u20b9' + inr[1][0] + '-' + inr[1][1] + ' LPA \u00b7 ' +
    'Lead: $' + newUsd[2] + 'K+ / \u20b9' + lead + ' LPA+';
}

