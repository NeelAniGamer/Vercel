function matchSlugs(rules, text) {
  const out = [];
  for (const r of rules) if (r.re.test(text)) out.push(r.slug);
  return out;
}

function interestTags(career) {
  const text = [
    career.title,
    career.catName,
    (career.roles || []).join(' '),
    (career.desc || '').slice(0, 300)
  ].join(' ').toLowerCase();

  const tags = matchSlugs(INTEREST_RULES, text);

  // Category floor: every career gets at least one home, so no interest filter
  // can end up empty and no career ends up untagged.
  const fallback = {
    tech: 'tech', health: 'health', eng: 'machines', space: 'science',
    eco: 'outdoors', science: 'science', biz: 'business', law: 'law',
    creative: 'design', edu: 'teaching', trades: 'machines', service: 'people'
  }[career.cat];
  if (fallback && !tags.includes(fallback)) tags.unshift(fallback);
  if (!tags.length) tags.push('people');
  return [...new Set(tags)].slice(0, 5);
}

function degreeTags(career, eduSlug) {
  const text = [
    career.title,
    (career.education && career.education.undergradDegrees || []).join(' '),
    (career.education && career.education.postgradDegrees || []).join(' ')
  ].join(' ').toLowerCase();

  const tags = matchSlugs(DEGREE_RULES, text);

  // Vocational routes come from the BLS entry requirement rather than a degree
  // name, so trades that never mention a bachelor still show up.
  if (eduSlug === 'nodegree' || eduSlug === 'diploma') tags.push('vocational');
  if (!tags.length) tags.push('any');
  return [...new Set(tags)].slice(0, 5);
}

function eduLevelFor(career) {
  const b = bls[career.id];
  const raw = b && b.entryEducation ? b.entryEducation : '';
  if (/no formal|high school/i.test(raw)) return 'nodegree';
  if (/postsecondary nondegree|associate|some college/i.test(raw)) return 'diploma';
  if (/master/i.test(raw)) return 'master';
  if (/doctoral|professional/i.test(raw)) return 'doctorate';
  if (/bachelor/i.test(raw)) return 'bachelor';

  const text = ((career.education && career.education.undergradDegrees || []).join(' ') + ' ' +
    (career.education && career.education.postgradDegrees || []).join(' ')).toLowerCase();
  if (/ph\.?d|mbbs|\bmd\b|\bbds\b|ll\.?b|bvsc|doctor of/.test(text)) return 'doctorate';
  if (/m\.?ba|master|m\.?tech|m\.?des|m\.?phil|\bm\.?s\b/.test(text)) return 'master';
  if (/diploma|\biti\b|polytechnic|apprentice/.test(text)) return 'diploma';
  return 'bachelor';
}

