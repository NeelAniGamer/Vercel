// Derive the exact set of (type, target) pairs game_core._checkTasks completes.
// The result is written to Traffic/unhandled-task-targets.js so the runtime can
// guarantee no objective hangs forever, without hand-maintaining a second list.
const fs = require('fs')
const path = require('path')

const trafficRoot = path.join(__dirname, '..')
const core = fs.readFileSync(path.join(trafficRoot, 'game_core.js'), 'utf8')

const start = core.indexOf('_checkTasks() {')
const end = core.indexOf('// Safety net for objectives that declare a target', start)
if (start < 0 || end < 0) {
  console.error('could not locate the _checkTasks switch')
  process.exit(1)
}
const body = core.slice(start, end)

const pairs = new Set()
let currentType = null
for (const line of body.split('\n')) {
  const c = line.match(/case '(\w+)':/)
  if (c) { currentType = c[1]; continue }
  if (!currentType) continue
  const t = line.match(/t\.target === '([a-z_0-9]+)'/)
  if (t) { pairs.add(currentType + '/' + t[1]); continue }
  if (/t\.target\.indexOf\('checkpoint_'\)/.test(line)) pairs.add(currentType + '/checkpoint_N')
}

// Objectives that need more than a one-line test live in task-evaluators.js and
// are dispatched by a `type/target` key rather than an inline comparison. They
// are handled too, so they must be counted here or the runtime safety net would
// paper over real branches with a 3-second placeholder.
const evaluatorsPath = path.join(trafficRoot, 'task-evaluators.js')
let evaluatorCount = 0
if (fs.existsSync(evaluatorsPath)) {
  const src = fs.readFileSync(evaluatorsPath, 'utf8')
  for (const m of src.matchAll(/^\s*'([a-z_]+)\/([a-z_0-9]+)':\s*function/gm)) {
    pairs.add(m[1] + '/' + m[2])
    evaluatorCount++
  }
  // Evaluators reached through a shared helper, keyed on a variable.
  for (const m of src.matchAll(/'(reach\/[a-z_0-9]+)':\s*function\s*\([^)]*\)\s*\{\s*return\s+([a-zA-Z]+)\(/g)) {
    pairs.add(m[1])
    evaluatorCount++
  }
}

// Targets every declared level task uses.
const levelsDir = path.join(trafficRoot, 'levels')
const used = new Map()
for (const f of fs.readdirSync(levelsDir).filter(x => x.endsWith('.js'))) {
  const src = fs.readFileSync(path.join(levelsDir, f), 'utf8')
  for (const m of src.matchAll(/type:\s*'(\w+)',\s*target:\s*'([a-z_0-9]+)'/g)) {
    const key = m[1] + '/' + m[2]
    if (!used.has(key)) used.set(key, [])
    used.get(key).push(f)
  }
}

const unhandled = []
for (const [key, files] of used) {
  if (pairs.has(key)) continue
  // enter_vehicle completes on any target, and checkpoint_N is a wildcard.
  const [type, target] = [key.slice(0, key.indexOf('/')), key.slice(key.indexOf('/') + 1)]
  if (type === 'enter_vehicle') continue
  if (type === 'reach' && /^checkpoint_\d+$/.test(target)) continue
  unhandled.push({ type, target, levels: [...new Set(files)] })
}

unhandled.sort((a, b) => (a.type + a.target).localeCompare(b.type + b.target))

const out = `// GENERATED by Traffic/tools/gen-unhandled-task-targets.js. Do not edit by hand.
// Objectives that game_core._checkTasks has no branch for. They are completed
// as placeholders so a level can never become uncompletable, and they are
// reported once each in the console so the gap stays discoverable.
window.UNHANDLED_TASK_DWELL_FRAMES = 180; // ~3 seconds at 60fps
window.UNHANDLED_TASK_TARGETS = [
${unhandled.map(u => `  { type: '${u.type}', target: '${u.target}' }, // ${u.levels.length} level(s)`).join('\n')}
];
`
fs.writeFileSync(path.join(trafficRoot, 'unhandled-task-targets.js'), out)

console.log(`handled (type/target) pairs: ${pairs.size} (${evaluatorCount} from task-evaluators.js)`)
console.log(`declared objectives: ${used.size}`)
console.log(`unhandled: ${unhandled.length}`)
for (const u of unhandled) console.log(`  ${u.type}/${u.target}  (${u.levels.length} levels)`)
